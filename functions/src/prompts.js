function getPrompt(operation) {
  const prompt = PROMPTS[operation];
  if (!prompt) return null;
  const prefix = prompt.role ? `${prompt.role}\n` : "";
  return { ...prompt, instructions: `${prefix}${BASE_INSTRUCTIONS}\n${prompt.task}` };
}

