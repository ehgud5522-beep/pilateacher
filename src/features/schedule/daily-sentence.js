const pad = (value) => String(value).padStart(2, "0");
/** 그 날짜의 기기 기준 "YYYY-MM-DD". */
export const dayKey = (date = new Date()) => `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}`;

/* 1970-01-05 는 월요일 -- 주 번호를 월요일 기준으로 센다. */
const MONDAY_EPOCH = Date.UTC(1970, 0, 5);
const weekNumber = (date) => Math.floor((Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) - MONDAY_EPOCH) / (7 * 86400000));

/**
 * 오늘의 한 문장. 날짜만으로 정해진다.
 * @returns {{ kind: string, label: string, message: string, action: string, day: string }}
 */
export function dailySentence(date = new Date()) {
  const weekday = date.getDay();
  const kind = WEEKDAY_KIND[weekday];
  const list = SENTENCES[kind];
  const week = weekNumber(date);
  /* 한 주에 두 번 나오는 종류(회원 관리 화 · 목, 주말 토 · 일)는 두 칸씩 넘어간다 -- 같은 주에 겹치지 않게. */
  const twice = kind === SENTENCE_KIND.CARE || kind === SENTENCE_KIND.CHEER;
  const slot = twice ? (weekday === 4 || weekday === 0 ? 1 : 0) : 0;
  const index = (((twice ? week * 2 + slot : week) % list.length) + list.length) % list.length;
  const picked = list[index];
  return { kind, label: SENTENCE_KIND_LABEL[kind], message: picked.message, action: picked.action, day: dayKey(date) };
}

/* ── 오늘은 닫기 (이 기기) ── */
export const DAILY_SENTENCE_HIDE_KEY = "pilateacher.dailySentence.hiddenOn";

export function isHiddenToday(storage, date = new Date()) {
  try { return text(storage?.getItem?.(DAILY_SENTENCE_HIDE_KEY)) === dayKey(date); } catch (_error) { return false; }
}

export function hideToday(storage, date = new Date()) {
  try { storage?.setItem?.(DAILY_SENTENCE_HIDE_KEY, dayKey(date)); } catch (_error) { /* 저장 못 하면 이번 화면에서만 닫힌다 */ }
}
