/**
 * 겹쳐 열리는 전면 오버레이가 어느 순서로 쌓이는가.
 *
 * 탭 위를 통째로 덮는 화면들 -- 회원 상세 · 이달 예상 급여 · 출석 체크 ·
 * 담당 변경 -- 은 App 의 같은 자리에 **형제로** 그려진다. 1.1.42 까지 넷이
 * 모두 z-50 이었고, 값이 같으면 순서를 정하는 것은 App.jsx 에서 누가 먼저
 * 적혀 있느냐뿐이다.
 *
 * 그래서 틀렸다. 회원 상세에서 "담당 변경" 을 누르면 담당 변경이 회원 상세
 * **뒤에서** 열렸다 -- 담당 변경 블록이 파일에서 먼저 적혀 있었기 때문이다.
 * 누른 사람에게는 아무 일도 일어나지 않은 것으로 보이고, 회원 상세를 X 로
 * 닫아야 그제서야 나타났다 (2026-10-27 대표 보고).
 *
 * 그래서 쌓이는 순서를 DOM 순서에서 떼어 여기 적는다. 새 전면 오버레이를
 * 붙일 때는 이 표에 한 줄을 더하고, **그것이 무엇 위에 서야 하는지** 적는다.
 * App.jsx 의 JSX 순서는 더 이상 답이 아니다.
 */

/**
 * 일반 바텀시트(App.jsx 의 `Sheet`)가 쓰는 값.
 *
 * 표가 이것을 알아야 "회원 상세 안에서 시트가 열려 있어도 담당 변경이 그
 * 위" 를 말할 수 있다. 회원 상세는 자기 z-index 로 쌓임 맥락을 만들므로,
 * 그 안의 `position: fixed` 시트도 회원 상세 층 안에 갇힌다.
 */
export const SHEET_Z = 60;

export const OVERLAY_LAYER = Object.freeze({
  /** 탭 위에 한 장. 이달 예상 급여 · 출석 체크 -- 서로 겹쳐 열리지 않는다. */
  PAGE: 50,
  /** 회원 상세. 출석 체크에서도 열리므로 PAGE 위에 선다. */
  DETAIL: 56,
  /** 회원 상세 위에서 누르는 것. 담당 변경 -- 상세가 안에서 연 시트(SHEET_Z)
      보다도 위여야 한다. */
  ACTION: 70,
  /** 결과를 알리는 한 줄. **무엇 위에서 눌렀든 보여야 한다** -- 안 보이면
      누른 사람은 아무 일도 안 일어난 줄 안다. 그래서 늘 맨 위다. */
  TOAST: 80,
});

/** 쌓이는 순서. 뒤의 것이 앞의 것 위에 선다. */
export const OVERLAY_OPEN_ORDER = Object.freeze(["PAGE", "DETAIL", "ACTION", "TOAST"]);

/**
 * 층 이름을 z-index 로. 이름을 틀리면 **조용히 0 이 되는 대신 터진다** --
 * 조용한 0 은 정확히 고치려던 그 버그(뒤에서 열림)로 되돌아가는 길이다.
 *
 * @param {string} layer
 * @returns {number}
 */
export function overlayZ(layer) {
  const z = OVERLAY_LAYER[layer];
  if (typeof z !== "number") throw new Error(`Unknown overlay layer: ${layer}`);
  return z;
}
